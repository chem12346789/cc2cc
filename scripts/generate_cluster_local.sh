#!/usr/bin/env bash

set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
OUTPUT="${SCRIPT_DIR}/cluster.local.sh"
FORCE=0

while (($#)); do
    case "$1" in
        --output)
            (($# >= 2)) || { echo "Missing path after --output" >&2; exit 2; }
            OUTPUT="$2"
            shift 2
            ;;
        --force)
            FORCE=1
            shift
            ;;
        *)
            echo "Usage: $0 [--output PATH] [--force]" >&2
            exit 2
            ;;
    esac
done

if [[ -e "${OUTPUT}" && "${FORCE}" != "1" ]]; then
    echo "${OUTPUT} already exists; choose --output or pass --force to replace it." >&2
    exit 1
fi

read_setting() {
    local variable="$1"
    local prompt="$2"
    local default="$3"
    local answer

    read -r -p "${prompt} [${default}]: " answer
    printf -v "${variable}" '%s' "${answer:-${default}}"
}

python_default="$(command -v python3 || command -v python)"
read_setting python_bin "Python interpreter" "${python_default}"
read_setting pyscf_tmpdir "PySCF scratch directory" "${TMPDIR:-${HOME}/tmp}"
read_setting python_path "Additional Python path (absolute; optional)" ""
read_setting library_path "Additional library path (absolute; optional)" ""
read_setting numa_map "GPU-to-NUMA mapping (GPU:node pairs; blank disables binding)" ""
read_setting array_concurrency "Maximum concurrent slots override (optional)" ""
read_setting min_slots "Minimum usable slots required before submitting" "1"

if [[ -n "${array_concurrency}" && ! "${array_concurrency}" =~ ^[1-9][0-9]*$ ]]; then
    echo "Maximum concurrent slots override must be a positive integer." >&2
    exit 2
fi
if [[ ! "${min_slots}" =~ ^[1-9][0-9]*$ ]]; then
    echo "Minimum usable slots must be a positive integer." >&2
    exit 2
fi
if [[ -n "${array_concurrency}" ]] && ((min_slots > array_concurrency)); then
    echo "Minimum usable slots must not exceed the maximum concurrent slots override." >&2
    exit 2
fi
if [[ -n "${numa_map}" ]]; then
    IFS=, read -r -a numa_mappings <<< "${numa_map}"
    for mapping in "${numa_mappings[@]}"; do
        if [[ ! "${mapping}" =~ ^[0-9]+:[0-9]+$ ]]; then
            echo "NUMA mapping must be comma-separated GPU:node pairs." >&2
            exit 2
        fi
    done
fi

temporary="$(mktemp "${OUTPUT}.tmp.XXXXXX")"
trap 'rm -f -- "${temporary}"' EXIT
{
    printf '# Generated by scripts/generate_cluster_local.sh\n'
    printf 'export PYTHON_BIN=%q\n' "${python_bin}"
    printf 'export PYSCF_TMPDIR=%q\n' "${pyscf_tmpdir}"
    if [[ -n "${python_path}" ]]; then
        printf 'export PYTHONPATH=%q${PYTHONPATH:+:$PYTHONPATH}\n' "${python_path}"
    fi
    if [[ -n "${library_path}" ]]; then
        printf 'export LD_LIBRARY_PATH=%q${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}\n' "${library_path}"
    fi
    printf 'export GPU_NUMA_NODE_MAP=%q\n' "${numa_map}"
    if [[ -n "${array_concurrency}" ]]; then
        printf 'export CC2CC_ARRAY_CONCURRENCY=%q\n' "${array_concurrency}"
    fi
    printf 'export CC2CC_MIN_SLOTS=%q\n' "${min_slots}"
} > "${temporary}"
mv -- "${temporary}" "${OUTPUT}"
trap - EXIT

echo "Wrote ${OUTPUT}"
